package security

import "testing"

func TestPasswordHashRoundTrip(t *testing.T) {
	password := "correct-horse-battery-staple-82!"
	hash, err := HashPassword(password)
	if err != nil {
		t.Fatalf("HashPassword returned an error: %v", err)
	}
	if !VerifyPassword(password, hash) {
		t.Fatal("VerifyPassword rejected the correct password")
	}
	if VerifyPassword(password+"x", hash) {
		t.Fatal("VerifyPassword accepted an incorrect password")
	}
}

func TestPasswordHashRejectsShortInput(t *testing.T) {
	if _, err := HashPassword("too-short"); err == nil {
		t.Fatal("HashPassword accepted a short password")
	}
}

func TestPasswordHashRejectsMalformedValue(t *testing.T) {
	for _, value := range []string{"", "pbkdf2_sha256:0:a:b", "pbkdf2_sha256:not-a-number:a:b", "pbkdf2_sha256:310000:bad:bad"} {
		if VerifyPassword("any password", value) {
			t.Fatalf("VerifyPassword accepted malformed hash %q", value)
		}
	}
}

func TestPasswordHashCompatibleWithPythonPBKDF2(t *testing.T) {
	encoded := "pbkdf2_sha256:310000:MDEyMzQ1Njc4OWFiY2RlZg:XuBz23y9DlMsELW3aspb4qykHJMbRj9r8FMAbmbbs3k"
	if !VerifyPassword("cross-language test password!", encoded) {
		t.Fatal("Go verifier rejected a standard PBKDF2-SHA256 hash generated by Python")
	}
}
